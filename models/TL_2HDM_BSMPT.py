"""2HDM model variant that swaps the radiation bath DOFs for BSMPT's tabulation.

Subclasses ``models/TL_2HDM.py`` and overrides only ``geff`` (the effective
relativistic DOF count) and ``radiationEnergyDensity`` so the comparison
against BSMPT in figs. 15-16 is fair (matched degrees of freedom).
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import numpy as np
from scipy.interpolate import interp1d

REPO_ROOT = Path(__file__).resolve().parents[1]
_BASE_MODEL_PATH = REPO_ROOT / "models" / "TL_2HDM.py"
_SPEC = importlib.util.spec_from_file_location("tl_2hdm_base_for_bsmpt", _BASE_MODEL_PATH)
if _SPEC is None or _SPEC.loader is None:
    raise ImportError(f"Could not load base 2HDM model from {_BASE_MODEL_PATH}")
_BASE = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(_BASE)
_BaseR2HDM = _BASE.R2HDM


class R2HDM(_BaseR2HDM):
    """2HDM with BSMPT-tabulated g_eff and matched radiation energy density."""

    def geff(self, T):
        TmeV = T * self.conversionFactor * 1000.0
        TQCD = 214.0
        if TmeV < _GstarLow.x[0]:
            return _GstarLow.y[0]
        if TmeV < TQCD:
            return _GstarLow(TmeV)
        if TmeV > _GstarHigh.x[-1]:
            return _GstarHigh.y[-1]
        THigh = 1_000_000.0
        NHiggs = 8  # 2 Higgs doublets
        gb = 8 * 2 + 4 * 2 + NHiggs
        gf = 6 * 3 * 2 * 2 + 3 * 2 * 2 + 3 * 2
        geff = gb + 7.0 / 8.0 * gf
        return (
            np.power(TmeV / TQCD, np.log(geff / _GstarHigh(THigh)) / np.log(THigh / TQCD))
            * _GstarHigh(TmeV)
        )

    def radiationEnergyDensity(self, X: np.ndarray, T: float, include_decoupled: bool = True) -> float:
        return np.pi**2 / 30.0 * self.geff(T) * T**4


