"""The headline numbers of the paper recomputed from paper/data, into output/numbers.json and output/numbers.tex (one
\\newcommand per number).

Sources (paper/data):
    plane_scan_u1.npz        likelihood maps of the default and the alternatives (G x log10 v grid)
    marginal_foreground.npz  B1 and B2 marginalised over the astrophysical priors (through make_figures.budget_rows)
    best_fits.json           continuous best fits
    preference_tau0.1.json, preference_tau4.json   local significances of the binary-only fits
Definitions are those of figs/make_figures.py (intervals: equal-tailed marginal 68 %, D: Mahalanobis distance of the
posterior means with the default covariance), imported from there so the paper and this file cannot diverge.
    python make_numbers.py"""
import json
import os
import sys

import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import paths  # noqa: E402
sys.path.insert(0, os.path.join(paths.PAPER, "figs"))
import make_figures as mf  # noqa: E402
import table_preference as tp  # noqa: E402

A = N65 = paths.DATA
OUTPUT = os.path.join(HERE, "output")
out = {}


def put(key, value, fmt, unit="", source=""):
    out[key] = dict(value=float(value), text=format(value, fmt), unit=unit, source=source)


# default regions and best fits
d = np.load(os.path.join(A, "plane_scan_u1.npz"), allow_pickle=True)
G, L = d["G"], d["LOGV"]
for ds in ("NG15", "IPTA2"):
    _, p = mf._levels(d[ds][0])
    g = mf._interval(p, G, 0); lv = mf._interval(p, L, 1)
    put(f"{ds}_g1_lo", g[0], ".3f", source="plane_scan_u1.npz, equal-tailed 68 %")
    put(f"{ds}_g1_hi", g[1], ".3f", source="plane_scan_u1.npz")
    put(f"{ds}_v1_lo", 10 ** lv[0], ".2g", "GeV", "plane_scan_u1.npz")
    put(f"{ds}_v1_hi", 10 ** lv[1], ".2g", "GeV", "plane_scan_u1.npz")
bf = json.load(open(os.path.join(A, "best_fits.json")))["nlo"]
for ds in ("NG15", "IPTA2"):
    put(f"{ds}_bf_g", bf[ds]["at"][0], ".3f", source="best_fits.json")
    put(f"{ds}_bf_v", 10 ** bf[ds]["at"][1], ".2g", "GeV", "best_fits.json")

# joint fit of NANOGrav and IPTA (parameter goodness of fit, two shared parameters)
J = d["NG15"][0] + d["IPTA2"][0]
chi2 = 2 * (np.nanmax(d["NG15"][0]) + np.nanmax(d["IPTA2"][0]) - np.nanmax(J))
ij = np.unravel_index(np.nanargmax(J), J.shape)
put("joint_chi2", chi2, ".1f", source="plane_scan_u1.npz grid maxima")
put("joint_sigma", stats.norm.isf(stats.chi2.sf(chi2, 2) / 2), ".1f", "sigma", "two-sided, 2 dof")
put("joint_g", G[ij[0]], ".3f"); put("joint_v", 10 ** L[ij[1]], ".2g", "GeV")

# shifts of the alternatives (the budget figure, make_figures.budget_rows)
for ds in ("NG15", "IPTA2"):
    for row in mf.budget_rows(ds)[0]:
        name, dist = row[1], row[5]
        if dist is None or not np.isfinite(dist):
            continue
        key = f"{ds}_D_" + "".join(c if c.isalnum() else "_" for c in name).strip("_")
        put(key, dist, ".1f", source="make_figures.budget_rows")

# local significances, as table_preference.py computes them: for IPTA the maximum with the phase
# transition lowered by the grid scatter of the IPTA likelihood
for tag, fn in (("tau01", "preference_tau0.1.json"), ("tau4", "preference_tau4.json")):
    P = json.load(open(os.path.join(N65, fn)))
    for lik in P:
        for prior, r in P[lik].items():
            gain = r["gain"] - (tp.IPTA_SCATTER if lik == "ipta2" else 0.0)
            put(f"pref_{tag}_{lik}_{prior}", float(tp.sigma_from_gain(gain, 2)), ".1f", "sigma", fn)

# Delta N_eff of the GW background over the plane
put("dneff_max", np.nanmax(d["dneff_gw"]), ".3f", source="plane_scan_u1.npz dneff_gw")

json.dump(out, open(os.path.join(OUTPUT, "numbers.json"), "w"), indent=1)
with open(os.path.join(OUTPUT, "numbers.tex"), "w") as f:
    f.write("% generated by reproduce/numbers/make_numbers.py; do not edit\n")
    for k, v in out.items():
        name = "num" + "".join(w.capitalize() for w in k.replace("0", "Zero").replace("1", "One").replace("2", "Two")
                               .replace("3", "Three").replace("4", "Four").replace("5", "Five").replace("6", "Six")
                               .replace("7", "Seven").replace("8", "Eight").replace("9", "Nine").split("_"))
        f.write(f"\\newcommand{{\\{name}}}{{{v['text']}}}  % {k} [{v['unit']}] {v['source']}\n")
print(f"wrote {len(out)} numbers to numbers.json and numbers.tex")
